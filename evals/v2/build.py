#!/usr/bin/env python3
"""Generate every eval suite from patterns.json (spec 001 section 4).

Suites are generated, never hand-edited, so the guard's source of truth and the files the
engine reads cannot drift apart.

Three suites, one per question the sweep asks:

  consultation/  on-topic prompts   -- is the skill opened?
  restraint/     off-topic prompts  -- is it left alone?
  correctness/   flag questions     -- is the answer right?

Correctness used to be twelve single-case suites, one per assertion, because a suite's
checks applied to all of its cases and there was no way to say otherwise. `[[check]]`
entries now take a `cases` list (R6), so the twelve collapse into one suite whose checks
are each scoped to the case they belong to.

Skill invocation is no longer written out as a check. The `should_trigger` column of the
CSV generates it, with matching polarity (R7), so the column that used to assert nothing
is now the thing being asserted. Writing an explicit `skill_invoked` alongside it would be
redundant at best and rejected as a contradiction at worst.
"""
import csv
import json
import pathlib
import shutil
import sys

HERE = pathlib.Path(__file__).resolve().parent

HEADER = (
    "# GENERATED by build.py from patterns.json - do not edit by hand.\n"
    "#\n"
    "# Skill invocation is not listed here. Each case's `should_trigger` column\n"
    "# generates a `skill_invoked` check with matching polarity (R7).\n"
)


def write_csv(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, quoting=csv.QUOTE_MINIMAL, lineterminator="\n")
        w.writerow(["id", "prompt", "should_trigger", "tags", "workspace_subdir"])
        w.writerows(rows)


def scope(case_id):
    """Restrict a check to one case. Absent, a check applies to every case."""
    return f'cases = ["{case_id}"]\n'


def command_contains(pattern, case_id):
    return (
        "\n[[check]]\n"
        'name = "command_contains"\n'
        f'pattern = "{pattern}"\n'
        "required = true\n" + scope(case_id)
    )


def must_not_say(pattern, case_id):
    """A negative text expectation: the answer must not contain `pattern`."""
    return (
        "\n[[check]]\n"
        'name = "trigger_expectation"\n'
        f'pattern = "{pattern}"\n'
        "expected = false\n"
        "required = true\n" + scope(case_id)
    )


def tool_cap(limit):
    return "\n[[check]]\n" 'name = "max_tool_calls"\n' f"limit = {limit}\n" "required = true\n"


def main():
    pats = json.loads((HERE / "patterns.json").read_text())
    cap = pats["max_tool_calls"]

    # Consultation: on-topic prompts, the skill document must be opened.
    # should_trigger=true carries that assertion; only the budget is written out.
    d = HERE / "consultation"
    write_csv(
        d / "prompts.csv",
        [[cid, prompt, "true", tag, ""] for cid, prompt, tag in pats["consultation"]],
    )
    (d / "checks.toml").write_text(HEADER + tool_cap(cap))

    # Restraint: off-topic prompts, the skill document must NOT be opened.
    # should_trigger=false is the entire suite, so the file is a header and nothing else.
    # An empty check list is valid; the generated check still runs.
    d = HERE / "restraint"
    write_csv(
        d / "prompts.csv",
        [[cid, prompt, "false", tag, ""] for cid, prompt, tag in pats["restraint"]],
    )
    (d / "checks.toml").write_text(HEADER)

    # Correctness: one suite, one check per case, each scoped with `cases` (R6).
    #
    # These prompts are on-topic, so should_trigger stays true and each case also gets the
    # generated skill_invoked check. That is a second, independent assertion, not a
    # dilution of this one: `eval scorecard` keeps a rate per check type, so consulting the
    # skill and answering correctly are reported as the separate things they are.
    d = HERE / "correctness"
    if d.exists():
        shutil.rmtree(d)
    write_csv(
        d / "prompts.csv",
        [[c["id"], c["prompt"], "true", "correctness", ""] for c in pats["correctness"]],
    )
    body = HEADER
    for case in pats["correctness"]:
        for pat in case.get("require", []):
            body += command_contains(pat, case["id"])
        for pat in case.get("forbid", []):
            body += must_not_say(pat, case["id"])
    body += tool_cap(cap)
    (d / "checks.toml").write_text(body)

    print(
        f"generated 3 suites: consultation ({len(pats['consultation'])} cases), "
        f"restraint ({len(pats['restraint'])} cases), "
        f"correctness ({len(pats['correctness'])} cases)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
