#!/usr/bin/env python3
"""Generate every eval suite from patterns.json (spec 001 §4).

Suites are generated, never hand-edited, so the guard's source of truth and the files the
engine reads cannot drift apart.
"""
import csv
import json
import pathlib
import shutil
import sys

HERE = pathlib.Path(__file__).resolve().parent

def write_csv(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, quoting=csv.QUOTE_MINIMAL, lineterminator="\n")
        w.writerow(["id", "prompt", "should_trigger", "tags", "workspace_subdir"])
        w.writerows(rows)

def trigger_check(pattern, expected):
    return (
        "[[check]]\n"
        'name = "trigger_expectation"\n'
        f'pattern = "{pattern}"\n'
        f"expected = {str(expected).lower()}\n"
        "required = true\n"
    )

def tool_cap(limit):
    return (
        "\n[[check]]\n"
        'name = "max_tool_calls"\n'
        f"limit = {limit}\n"
        "required = true\n"
    )

def main():
    pats = json.loads((HERE / "patterns.json").read_text())
    consult = pats["consultation_pattern"]
    cap = pats["max_tool_calls"]
    header = "# GENERATED by build.py from patterns.json — do not edit by hand.\n"

    # Consultation: on-topic prompts, the skill document must be opened.
    d = HERE / "consultation"
    write_csv(d / "prompts.csv", [[cid, prompt, "true", tag, ""] for cid, prompt, tag in pats["consultation"]])
    (d / "checks.toml").write_text(header + trigger_check(consult, True) + tool_cap(cap))

    # Restraint: off-topic prompts, the skill document must NOT be opened.
    d = HERE / "restraint"
    write_csv(d / "prompts.csv", [[cid, prompt, "false", tag, ""] for cid, prompt, tag in pats["restraint"]])
    (d / "checks.toml").write_text(header + trigger_check(consult, False))

    # Correctness: one suite per assertion, because checks are global (spec 001 C1).
    root = HERE / "correctness"
    if root.exists():
        shutil.rmtree(root)
    for case in pats["correctness"]:
        d = root / case["id"]
        write_csv(d / "prompts.csv", [[case["id"], case["prompt"], "true", "correctness", ""]])
        body = header
        for pat in case.get("require", []):
            body += "\n[[check]]\n" 'name = "command_contains"\n' f'pattern = "{pat}"\n' "required = true\n"
        for pat in case.get("forbid", []):
            body += "\n" + trigger_check(pat, False)
        body += tool_cap(cap)
        (d / "checks.toml").write_text(body)

    n = 2 + len(pats["correctness"])
    print(f"generated {n} suites: consultation ({len(pats['consultation'])} cases), "
          f"restraint ({len(pats['restraint'])} cases), "
          f"correctness ({len(pats['correctness'])} single-case suites)")
    return 0

if __name__ == "__main__":
    sys.exit(main())
